# ── Environment detection ───────────────────────────────────────────────────
def _has_display() -> bool:
    """Return True if a GUI display is available (False in Colab / SSH)."""
    import os
    # Google Colab sets COLAB_RELEASE_TAG or runs inside ipykernel
    if "COLAB_RELEASE_TAG" in os.environ or "COLAB_GPU" in os.environ:
        return False
    # Linux without DISPLAY
    if os.name == "posix" and not os.environ.get("DISPLAY"):
        return False
    return True


def _has_cuda_gpu() -> bool:
    """Return True if dlib was built with CUDA support and a GPU is available."""
    try:
        import dlib
        return dlib.DLIB_USE_CUDA and dlib.cuda.get_num_devices() > 0
    except Exception:
        return False


HEADLESS = not _has_display()
GPU_AVAILABLE = _has_cuda_gpu()


# ── Constants ───────────────────────────────────────────────────────────────
# Bounding box colours (BGR for OpenCV)
COLOR_MATCH = (0, 0, 255)       # RED   — known prisoner
COLOR_UNKNOWN = (0, 255, 0)     # GREEN — unregistered face
COLOR_TEXT_BG = (0, 0, 0)       # Black background behind text
FONT = cv2.FONT_HERSHEY_SIMPLEX
FONT_SCALE = 0.55
FONT_THICKNESS = 2
BOX_THICKNESS = 2


