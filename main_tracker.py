"""
============================================================================
 main_tracker.py — Prisoner Identification in Surveillance Video
 Project : Prisoners' Identification in a Surveillance Environment
 Author  : Shreyash Dehury
============================================================================

 PURPOSE
 -------
 This is the core processing pipeline.  It reads an input CCTV-style
 video frame-by-frame, detects every face in each frame, compares each
 detected face against a database of pre-computed 128-d encodings
 (generated by `encode_faces.py`), and renders annotated bounding boxes:

   RED   box + name   →  verified match  (known prisoner)
   GREEN box + "Unknown" → no match found  (unregistered person)

 The processed video is simultaneously displayed on screen and (optionally)
 saved to disk as a new .mp4 file.

 TOLERANCE (SIMILARITY THRESHOLD)
 ────────────────────────────────
 The `--tolerance` parameter controls how strict the matching is.

   • Lower values (e.g. 0.45) → stricter matching, fewer false positives,
     but may miss true matches in poor-quality frames.  Recommended when
     False Acceptance Rate (FAR) must be minimised.

   • Higher values (e.g. 0.60) → more lenient, captures more true matches,
     but increases the risk of mis-identification.

   • Default: 0.50  — a balanced trade-off for cross-resolution scenarios
     (high-res mugshots vs. low-res surveillance footage).

 CROSS-RESOLUTION MATCHING NOTES
 ────────────────────────────────
 Surveillance cameras typically capture faces at much lower resolution
 than the mugshots used for enrolment.  To mitigate degradation:

   1. Frame up-scaling (optional): Before detection, the frame is resized
      by `--scale` factor.  Upscaling a 480p frame to ~720p can improve
      detection recall, at the cost of speed.

   2. Frame skipping: Processing every Nth frame (`--skip`) reduces
      computational load, enabling near-real-time playback on CPUs.

   3. Multi-sample enrolment: Using multiple mugshots per person
      (front, left, right profiles) in `encode_faces.py` builds a
      richer encoding set and improves recall at a given FAR.

 FALSE ACCEPTANCE RATE (FAR) TESTING
 ────────────────────────────────────
 After running the tracker, review the CSV log (`--log`) to compute:

   FAR = (# frames where an Unknown is labelled as Known) / (# total frames)

 Varying `--tolerance` across runs (0.40 → 0.60 in steps of 0.02) and
 plotting FAR vs. tolerance yields the system's ROC-like characteristic.

 USAGE
 -----
   python main_tracker.py -v input_videos/cctv_clip.mp4
   python main_tracker.py -v input_videos/cctv_clip.mp4 --tolerance 0.45
   python main_tracker.py -v input_videos/cctv_clip.mp4 --skip 3 --save
   python main_tracker.py -v input_videos/cctv_clip.mp4 --model cnn --scale 1.5

============================================================================
"""

